let current = localStorage.getItem('resq.lang') || 'en';

export const i18n = {
  get lang() {
    return current;
  },

  set(code) {
    if (!STRINGS[code]) return;
    current = code;
    localStorage.setItem('resq.lang', code);
    document.documentElement.lang = code;
    this.apply();
  },

  get chosen() {
    return localStorage.getItem('resq.lang') !== null;
  },

  get speechCode() {
    return (LANGUAGES.find((l) => l.code === current) || LANGUAGES[0]).speech;
  },

  /** Translate, falling back to English then to the key itself. */
  t(key) {
    return STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  },

  /** Re-translate every [data-i18n] node in the document. */
  apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((node) => {
      node.textContent = this.t(node.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
      node.placeholder = this.t(node.dataset.i18nPlaceholder);
    });
    root.querySelectorAll('[data-i18n-label]').forEach((node) => {
      node.setAttribute('aria-label', this.t(node.dataset.i18nLabel));
    });
  },
};

export const t = (key) => i18n.t(key);
